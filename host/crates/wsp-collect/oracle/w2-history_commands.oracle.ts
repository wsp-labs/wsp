  const uniq = [...new Set(LINES)];
  const pure = (fn: (l: string) => unknown) => uniq.map(l => ({ name: JSON.stringify(l), args: [l], out: plain(fn(l)) }));
  write("history_commands", {
    without_heredocs: pure(withoutHeredocs),
    split_commands: pure(splitCommands),
    command_words: pure(commandWords),
    command_names: pure(commandNames),
    install_names: pure(installNames),
  });
