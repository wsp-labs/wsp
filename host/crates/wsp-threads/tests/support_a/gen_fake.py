import re, sys, os
SRC = sys.argv[1]
files = {
 'WaitsCtx': 'threads/waits.rs', 'TrimmedCtx': 'threads/trimmed_row.rs', 'LaunchCtx': 'threads/launch.rs',
 'ActivityCtx': 'activity.rs', 'TurnsCtx': 'threads/turns.rs', 'SessionsCtx': 'threads/sessions.rs',
}
ASYNC = {'LaunchCtx','ActivityCtx','TurnsCtx','SessionsCtx'}

def methods(path, trait):
    s = open(os.path.join(SRC, path)).read()
    m = re.search(r'pub trait %s\b[^{]*\{(.*?)\n\}' % trait, s, re.S)
    body = m.group(1)
    out = []
    for line in body.split('\n'):
        line = line.strip()
        if not line.startswith(('fn ', 'async fn ')): continue
        assert line.endswith(';'), line
        out.append(line[:-1])
    return out

def split_args(a):
    parts, depth, cur = [], 0, ''
    prev = ''
    for ch in a:
        if ch in '<([': depth += 1
        if ch in ')]' or (ch == '>' and prev != '-'): depth -= 1
        prev = ch
        if ch == ',' and depth == 0:
            parts.append(cur.strip()); cur = ''
        else: cur += ch
    if cur.strip(): parts.append(cur.strip())
    return parts

def parse(sig):
    is_async = sig.startswith('async ')
    sig = sig[len('async '):] if is_async else sig
    name = re.match(r'fn (\w+)', sig).group(1)
    # args between first ( and matching )
    i = sig.index('('); depth = 0
    for j in range(i, len(sig)):
        if sig[j] == '(': depth += 1
        elif sig[j] == ')':
            depth -= 1
            if depth == 0: break
    args = split_args(sig[i+1:j])
    rest = sig[j+1:].strip()
    ret = rest[2:].strip() if rest.startswith('->') else ''
    args = [a for a in args if a != '&self']
    named = []
    for a in args:
        n, t = a.split(':', 1)
        named.append((n.strip(), t.strip()))
    return is_async, name, named, ret

def default(ret, trait, name):
    if ret == '': return '()'
    r = ret.replace(' ', '')
    if r == 'bool': return 'false'
    if r.startswith('Option<'): return 'None'
    if r.startswith('Vec<'): return 'Vec::new()'
    if r == 'String': return 'String::new()'
    if r in ('u32','u64','i64','f64','usize'): return '0 as %s' % r
    if r.startswith(('IndexMap<','IndexSet<')): return 'Default::default()'
    if r == 'Result<(),HostError>': return 'Ok(())'
    if r.startswith('Result<Option<'): return 'Ok(None)'
    if r.startswith('Result<Vec<'): return 'Ok(Vec::new())'
    if r == 'Result<bool,HostError>': return 'Ok(false)'
    if r == 'Result<String,HostError>': return 'Ok(String::new())'
    if r.startswith('Result<Map<String,Value>'): return 'Ok(Map::new())'
    if r == 'Joined': return 'done()'
    return 'panic!("FakeHost: %s::%s has no answer; set its hook")' % (trait, name)

STRY = ('&str', 'String', 'Option<&str>')
def logexpr(named):
    parts = []
    for n, t in named:
        if t in ('&str', 'String'): parts.append('%s.to_string()' % n)
        elif t == 'Option<&str>': parts.append('format!("{:?}", %s)' % n)
        elif t in ('bool','u32','u64','f64','i64'): parts.append('%s.to_string()' % n)
        elif t == 'AdapterAsk': parts.append('%s.named.clone().unwrap_or_default()' % n)
        elif t == '&RowAt': parts += ['format!("{:?}", %s.thread_id.as_deref())' % n, '%s.workspace_id.to_string()' % n]
    return 'vec![%s]' % ', '.join(parts)

HAND = open(sys.argv[2]).read()
hand = {}
for m in re.finditer(r'//@ (\w+)::(\w+)\n(.*?)//@end', HAND, re.S):
    hand[(m.group(1), m.group(2))] = m.group(3)

NOLOG = {'clock','sessions','records','ids','closing','live_entry','latest_on','held_at_close','checkpoints_landing','lead_asks','turn_groups','rows_on','thread_runs','running_on','launching_on','record','emit','pass'}
out = ['// Generated by gen_fake.py from the context traits; hand bodies come from fake_hand.rs.in. Do not edit.', '#![allow(unused_variables, unused_imports, clippy::all)]', 'use std::cell::RefCell;', 'use std::rc::Rc;', 'use std::sync::Arc;', '', 'use super::fake::*;', '']
for trait, path in files.items():
    ms = methods(path, trait)
    if trait in ASYNC: out.append('#[async_trait(?Send)]')
    out.append('impl %s for FakeHost {' % trait)
    for sig in ms:
        is_async, name, named, ret = parse(sig)
        out.append('    %s {' % sig)
        body = hand.get((trait, name))
        argnames = ', '.join(n for n, _ in named)
        argtypes = ', '.join(t for _, t in named)
        rett = ret if ret else '()'
        if is_async:
            ftype = "dyn Fn(%s) -> LocalBoxFuture<'static, %s>" % (argtypes, rett)
        else:
            ftype = 'dyn Fn(%s) -> %s' % (argtypes, rett)
        if name not in NOLOG:
            out.append('        self.hooks.log("%s", %s);' % (name, logexpr(named)))
        out.append('        if let Some(hook) = self.hooks.get::<%s>("%s::%s") {' % (ftype, trait, name))
        out.append('            return hook(%s)%s;' % (argnames, '.await' if is_async else ''))
        out.append('        }')
        if body is not None:
            out.append(body.rstrip('\n'))
        else:
            out.append('        %s' % default(ret, trait, name))
        out.append('    }')
    out.append('}')
    out.append('')
    # hook type aliases for tests
print('\n'.join(out))
