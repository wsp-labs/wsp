#[test]
fn number_text_is_what_string_of_a_number_is() {
    let wrong: Vec<String> = TEXT
        .iter()
        .filter(|(x, want)| number_string(*x) != *want)
        .map(|(x, want)| format!("{x:e}: node {want}, here {}", number_string(*x)))
        .collect();
    assert!(wrong.is_empty(), "{} of {} differ:\n{}", wrong.len(), TEXT.len(), wrong.join("\n"));
}

#[test]
fn a_radix_integer_reads_as_the_nearest_double() {
    let wrong: Vec<String> = RADIX
        .iter()
        .filter(|(text, want)| to_number(text).to_bits() != want.to_bits())
        .map(|(text, want)| format!("{text}: node {want}, here {}", to_number(text)))
        .collect();
    assert!(wrong.is_empty(), "{} of {} differ:\n{}", wrong.len(), RADIX.len(), wrong.join("\n"));
}
