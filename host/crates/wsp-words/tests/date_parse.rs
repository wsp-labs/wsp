#[test]
fn every_text_reads_as_node_reads_it() {
    let utc_here = DateZone::system().offset_seconds(1_760_000_000_000) == 0 && DateZone::system().offset_seconds(1_780_000_000_000) == 0;
    let mut wrong = Vec::new();
    let mut checked = 0;
    for (text, want, local) in CASES {
        if *local && !utc_here {
            continue;
        }
        checked += 1;
        let got = date_parse(text);
        if !(got == *want || (got.is_nan() && want.is_nan())) {
            wrong.push(format!("{text:?}: node {want}, here {got}"));
        }
    }
    assert!(checked > 100);
    assert!(wrong.is_empty(), "{} of {checked} differ:\n{}", wrong.len(), wrong.join("\n"));
}
